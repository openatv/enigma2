def getDABLanguageName(code):
	"""Both DVB and RTL-SDR expose decimal ETSI codes in sTagLanguageCode."""
	try:
		value = int(code)
	except (TypeError, ValueError):
		# Keep older RTL frontend names readable during staged upgrades.
		return code if isinstance(code, str) and code != "Unknown" else ""
	identifier = DAB_LANGUAGE_IDENTIFIERS.get(value)
	if identifier:
		return international.getLanguageTranslated(identifier) or _(LanguageCodes.get(identifier, ("",))[0])
	# These ETSI labels have no unambiguous identifier in the existing tables.
	return {
		64: _("Background sound/clean feed"),
		80: _("Sranan Tongo"),
		84: _("Serbo-Croat"),
		85: _("Rusyn"),
		94: _("Ndebele"),
		110: _("Gurani"),
		115: _("Dari"),
	}.get(value, "")
